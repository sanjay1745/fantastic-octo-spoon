import type { ImageSlot } from '../data/media'
import { srcSet } from '../lib/images'
import { asset } from '../lib/url'
import styles from './Media.module.css'

interface Props {
  slot: ImageSlot
  /** Fill the parent instead of using the slot's aspect ratio */
  fill?: boolean
  /** Above-the-fold images load eagerly */
  priority?: boolean
  /** Rendered width hint for the browser, e.g. '(min-width: 768px) 33vw, 80vw' */
  sizes?: string
  className?: string
}

/**
 * Renders a media slot: responsive AVIF/WebP once `src` is set, otherwise a clearly marked placeholder.
 * Files are generated by `npm run media` (see scripts/media.config.mjs).
 */
export default function Media({ slot, fill, priority, sizes = '100vw', className }: Props) {
  const cls = [styles.media, fill ? styles.fill : '', className].filter(Boolean).join(' ')
  const style = fill ? undefined : { aspectRatio: slot.aspect }

  if (!slot.src) {
    return (
      <div className={`${cls} ${styles.placeholder}`} style={style} role="img" aria-label={`Placeholder: ${slot.alt}`}>
        <span className={styles.tag}>Placeholder</span>
        <span className={styles.label}>{slot.label}</span>
      </div>
    )
  }

  return (
    <div className={cls} style={style}>
      <picture>
        <source type="image/avif" srcSet={srcSet(slot.src, 'avif')} sizes={sizes} />
        <img
          src={asset(`${slot.src}-1200.webp`)}
          srcSet={srcSet(slot.src, 'webp')}
          sizes={sizes}
          alt={slot.alt}
          loading={priority ? 'eager' : 'lazy'}
          decoding="async"
          style={slot.focus ? { objectPosition: slot.focus } : undefined}
          {...(priority ? { fetchPriority: 'high' as const } : {})}
        />
      </picture>
    </div>
  )
}
